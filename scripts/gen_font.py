"""Generate a 5x7 ASCII font table for the zclaw displays.

The output is a C file with one byte per column, so it can be dropped into
the firmware without pulling in a font library.
"""

from PIL import Image, ImageDraw, ImageFont
import sys

FIRST = 32
LAST = 126
W = 5
H = 7


def pick_font():
    candidates = [
        ("C:/Windows/Fonts/consola.ttf", 9),
        ("C:/Windows/Fonts/lucon.ttf", 9),
        ("C:/Windows/Fonts/cour.ttf", 10),
    ]
    for path, size in candidates:
        try:
            return ImageFont.truetype(path, size)
        except Exception:
            continue
    return ImageFont.load_default()


def render_glyph(font, ch):
    """Render one character and crop it to a 5x7 cell."""
    # A generous canvas, the glyph is cropped afterwards.
    img = Image.new("1", (16, 16), 0)
    draw = ImageDraw.Draw(img)
    draw.text((2, 2), ch, font=font, fill=1)

    bbox = img.getbbox()
    if bbox is None:
        return [0] * W

    glyph = img.crop(bbox)
    gw, gh = glyph.size

    # Scale the glyph down when it is taller or wider than the cell.
    if gw > W or gh > H:
        scale = min(W / gw, H / gh)
        new_w = max(1, int(gw * scale))
        new_h = max(1, int(gh * scale))
        glyph = glyph.resize((new_w, new_h), Image.LANCZOS)
        gw, gh = new_w, new_h

    # Center the glyph in the cell.
    ox = (W - gw) // 2
    oy = (H - gh) // 2

    canvas = Image.new("1", (W, H), 0)
    canvas.paste(glyph, (ox, oy))

    cols = []
    for x in range(W):
        bits = 0
        for y in range(H):
            if canvas.getpixel((x, y)):
                bits |= 1 << y
        cols.append(bits)
    return cols


def main():
    font = pick_font()
    out = sys.argv[1] if len(sys.argv) > 1 else "peripheral_font.c"

    table = []
    for code in range(FIRST, LAST + 1):
        table.append(render_glyph(font, chr(code)))

    with open(out, "w", newline="\n") as f:
        f.write("""// Generated by scripts/gen_font.py. Do not edit by hand.
//
// A 5x7 ASCII font. Every glyph is five columns and each column byte holds
// the eight pixels of that column, the lowest bit being the top row.

#include "peripheral_font.h"

static const uint8_t s_font[PERIPHERAL_FONT_GLYPH_COUNT][PERIPHERAL_FONT_GLYPH_WIDTH] = {
""")
        for i, cols in enumerate(table):
            code = FIRST + i
            f.write("    {")
            f.write(", ".join("0x%02X" % c for c in cols))
            f.write("}, // %d '%s'\n" % (code, chr(code)))
        f.write("};\n\n")
        f.write("""const uint8_t *font_get_glyph(char c)
{
    unsigned char code = (unsigned char)c;

    if (code < PERIPHERAL_FONT_FIRST_CHAR || code > PERIPHERAL_FONT_LAST_CHAR) {
        code = '?';
    }

    return s_font[code - PERIPHERAL_FONT_FIRST_CHAR];
}

int font_chars_per_line(int display_width)
{
    if (display_width <= 0) {
        return 0;
    }

    // One pixel of gap between the glyphs.
    int chars = display_width / (PERIPHERAL_FONT_GLYPH_WIDTH + 1);
    return chars > 0 ? chars : 1;
}
""")
    print("wrote", out, "with", len(table), "glyphs")


if __name__ == "__main__":
    main()
